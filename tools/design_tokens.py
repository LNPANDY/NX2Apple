#!/usr/bin/env python3
"""Writes the Mac launcher's Swift design tokens from frontend/design-tokens/tokens.json (LNPANDY/NX2Apple#1458).

The JSON is the one source: W3C Design Tokens Community Group format, with groups for colour, typography, spacing, radius,
control sizes and motion. This tool turns it into `frontend/Sources/NXLauncher/Generated/DesignTokens.swift` (the enums
`DS.Color`, `DS.Font`, `DS.Space`, `DS.Radius`, `DS.Control` and `DS.Motion`). The Qt and iOS front ends can get their own
writer from the same file later.

    python3 tools/design_tokens.py            # write the Swift file
    python3 tools/design_tokens.py --check    # exit 1 when the committed Swift file differs from what the JSON gives
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / 'frontend/design-tokens/tokens.json'
OUTPUT = ROOT / 'frontend/Sources/NXLauncher/Generated/DesignTokens.swift'

WEIGHTS = {100: 'ultraLight', 200: 'thin', 300: 'light', 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'heavy', 900: 'black'}


def camel(parts: list[str]) -> str:
    """`["text", "primary"]` -> `textPrimary`."""
    words = [p for p in parts if p]
    return words[0] + ''.join(w[:1].upper() + w[1:] for w in words[1:])


def leaves(group: dict, path: list[str] | None = None):
    """Every token of a group: (path, token), in file order."""
    path = path or []
    for key, value in group.items():
        if key.startswith('$') or not isinstance(value, dict):
            continue
        if '$value' in value:
            yield path + [key], value
        else:
            yield from leaves(value, path + [key])


def px(value: str) -> str:
    match = re.fullmatch(r'(-?\d+(?:\.\d+)?)px', value.strip())
    if not match:
        raise ValueError(f'not a px dimension: {value!r}')
    return match.group(1)


def ms(value: str) -> str:
    match = re.fullmatch(r'(\d+(?:\.\d+)?)ms', value.strip())
    if not match:
        raise ValueError(f'not a ms duration: {value!r}')
    return repr(float(match.group(1)) / 1000)


def color(value: str) -> str:
    match = re.fullmatch(r'#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?', value.strip())
    if not match:
        raise ValueError(f'not a #RRGGBB or #RRGGBBAA colour: {value!r}')
    rgb, alpha = match.group(1), match.group(2) or 'FF'
    return f'rgb(0x{rgb.upper()}, alpha: {round(int(alpha, 16) / 255, 3)})'


def doc(token: dict) -> str:
    text = token.get('$description', '')
    return f'        /// {text}\n' if text else ''


def render(tokens: dict) -> str:
    out = ['// Generated by tools/design_tokens.py from frontend/design-tokens/tokens.json. Do not edit: change the JSON and run the tool.',
           'import SwiftUI', 'import AppKit', '',
           '/// The launcher\'s design tokens. Screens use these, or the components built on them (DesignComponents.swift), never raw',
           '/// sizes or colours.',
           'package enum DS {']
    out += ['    /// Colours of the dark launcher.', '    package enum Color {']
    for path, token in leaves(tokens['color']):
        name = camel(path)
        out.append(doc(token) + f'        package static let {name} = SwiftUI.Color(nsColor: ns{name[:1].upper() + name[1:]})')
    for path, token in leaves(tokens['color']):
        name = camel(path)
        out.append(f'        package static let ns{name[:1].upper() + name[1:]} = {color(token["$value"])}')
    out += ['        private static func rgb(_ hex: UInt32, alpha: CGFloat) -> NSColor {',
            '            NSColor(srgbRed: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255, blue: CGFloat(hex & 0xFF) / 255, alpha: alpha)',
            '        }', '    }', '']
    out += ['    /// The type scale. Nothing is set below `footnote`.', '    package enum Font {']
    for path, token in leaves(tokens['typography']):
        value = token['$value']
        name = camel(path)
        weight = WEIGHTS[int(value['fontWeight'])]
        size = px(value['fontSize'])
        if value['fontFamily'] == 'Manrope':
            out.append(doc(token) + f'        package static let {name} = SwiftUI.Font.manrope({size}, .{weight})')
        else:
            out.append(doc(token) + f'        package static let {name} = SwiftUI.Font.system(size: {size}, weight: .{weight}, design: .monospaced)')
        out.append(f'        package static let {name}Size: CGFloat = {size}')
        out.append(f'        package static let {name}Tracking: CGFloat = {px(value.get("letterSpacing", "0px"))}')
    out += ['    }', '']
    for group, enum, summary in (('spacing', 'Space', 'The spacing scale: every gap and padding is one of these.'),
                                 ('radius', 'Radius', 'Corner radii.'),
                                 ('control', 'Control', 'Control and layout sizes.')):
        out += [f'    /// {summary}', f'    package enum {enum} {{']
        for path, token in leaves(tokens[group]):
            out.append(doc(token) + f'        package static let {camel(path)}: CGFloat = {px(token["$value"])}')
        out += ['    }', '']
    out += ['    /// Animation durations in seconds.', '    package enum Motion {']
    for path, token in leaves(tokens['motion']):
        out.append(doc(token) + f'        package static let {camel(path)}: Double = {ms(token["$value"])}')
    out += ['    }']
    if 'console' in tokens:
        out += render_console(tokens['console'])
    out += ['}', '']
    return '\n'.join(line for line in out)


def render_console(group: dict) -> list[str]:
    """The `console` group: console mode's own type scale, spacing, sizes, radii and scales, as `DS.Console`."""
    out = ['', '    /// Console mode, read from across a room: its own type scale and sizes.', '    package enum Console {']
    for key, sub in group.items():
        if key.startswith('$') or not isinstance(sub, dict):
            continue
        kind = sub.get('$type')
        name = 'Font' if kind == 'typography' else key[:1].upper() + key[1:]
        out.append(f'        package enum {name} {{')
        for path, token in leaves(sub):
            ident = camel(path)
            value = token['$value']
            text = token.get('$description', '')
            if text:
                out.append(f'            /// {text}')
            if kind == 'typography':
                size = px(value['fontSize'])
                weight = WEIGHTS[int(value['fontWeight'])]
                out.append(f'            package static let {ident} = SwiftUI.Font.manrope({size}, .{weight})')
                out.append(f'            package static let {ident}Size: CGFloat = {size}')
                out.append(f'            package static let {ident}Tracking: CGFloat = {px(value.get("letterSpacing", "0px"))}')
            elif kind == 'dimension':
                out.append(f'            package static let {ident}: CGFloat = {px(value)}')
            elif kind == 'number':
                if not isinstance(value, (int, float)):
                    raise ValueError(f'not a number: {value!r}')
                out.append(f'            package static let {ident}: CGFloat = {float(value)!r}')
            else:
                raise ValueError(f'console.{key}: unsupported $type {kind!r}')
        out.append('        }')
    out.append('    }')
    return out


def expected(path: Path = TOKENS) -> str:
    return render(json.loads(path.read_text(encoding='utf-8')))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true', help='do not write, exit 1 when the Swift file differs')
    args = parser.parse_args(argv)
    text = expected()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT.relative_to(ROOT)} is stale: run python3 tools/design_tokens.py', file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUTPUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
