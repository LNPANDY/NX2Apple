"""The process-boundary shim: everything `driver.py` cannot reach from inside Python.

`driver.py` can replace functions in the upstream module, but it cannot change what a *child*
Python process or a shell does. The upstream pipeline starts a lot of those:

* `dm/gfx/tools/dmsh_chain.py` calls `which spirv-cross` and `xcrun -sdk ... metal --version`
  while it fingerprints the shader chain — and it runs inside `dmsh_build.py`, `dmsh_facts.py`
  and the cache-key code of the NSP script itself.
* `dm/gfx/tools/ios_metal.py` and `dmsh_build.py` build the command lists
  `['xcrun', '-sdk', 'iphoneos', 'metal', ...]` and run them.
* `dm/gfx/tools/dmsh_chain.py` runs the committed `dmsh_xlate` apphost, which is a **Mach-O**
  executable and cannot start on Windows; the DLLs beside it are the same build, so
  `dotnet dmsh_xlate.dll` is equivalent and produces the same `--source-sha` output the lock
  file records.
* the pipeline spells the interpreter `python3` in places, which Windows does not have.

The clean way to cover all of that without editing upstream files is `sitecustomize.py`:
put this folder on `PYTHONPATH` and CPython imports it in **every** interpreter before the
program's own imports. It then rewrites `argv` at the `subprocess.Popen` boundary only.

`chrome/` holds the `xcrun.exe`-style stand-ins for the rare case where a tool is spawned
directly by name from a non-Python parent (the NSP script's own `shutil.which('xcodebuild')`
check, for instance). They are plain `.cmd` files so no compiler is needed to build them.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import toolchain as tc

SITECUSTOMIZE = 'sitecustomize.py'


# ---------------------------------------------------------------- the sitecustomize body

_SITECUSTOMIZE_SRC = r'''# Generated by nspb_qt.win.shim; imported by every Python the build starts.
# It rewrites macOS tool names at the subprocess boundary, leaving upstream sources untouched.
import os, sys

if os.name == 'nt' and not os.environ.get('NSPB_SHIM_OFF'):
    import shutil, subprocess

    # The shim lives in the app's data folder, but the modules it calls live in the package.
    # NSPB_WIN_DIR is written in when this file is generated; the fallback keeps a hand-copied
    # sitecustomize working when the variable is absent.
    _HERE = os.path.dirname(os.path.abspath(__file__))
    _PKG = os.environ.get('NSPB_WIN_DIR') or _HERE
    _XCRUN = os.path.join(_PKG, 'xcrun_shim.py')
    _BUILD_APP = os.path.join(_PKG, 'build_app.py')

    # the package root goes on sys.path so `import toolchain` / `import xcrun_shim` resolve, and
    # so `import nspb_qt.win` works from a child that wants the whole package
    for _p in (_PKG, os.path.dirname(_PKG)):
        if _p and _p not in sys.path:
            sys.path.insert(0, _p)

    # ---- text files written the way the pipeline expects them
    # The host compares lines of the pipeline's tables byte for byte; an inputs.tsv line ending
    # in "\r" did not match on the device (found by the reference implementation the hard way).
    import builtins, io
    _open = io.open

    def _lf_open(file, mode='r', buffering=-1, encoding=None, errors=None, newline=None,
                 closefd=True, opener=None):
        if newline is None and 'b' not in mode and any(c in mode for c in 'wax+'):
            newline = '\n'
        return _open(file, mode, buffering, encoding, errors, newline, closefd, opener)

    io.open = builtins.open = _lf_open

    # ---- os.replace as on a Mac
    # Windows refuses to replace a file another thread has open. The shader caches are
    # content-addressed, so two workers finishing the same entry is a legitimate race that
    # POSIX rename allows and Windows does not; retry, then accept an identical file.
    import time as _time
    _replace = os.replace

    def _win_replace(src, dst, *a, **k):
        for i in range(20):
            try:
                return _replace(src, dst, *a, **k)
            except PermissionError:
                if i == 19:
                    try:
                        if (os.path.isfile(dst) and os.path.getsize(dst) == os.path.getsize(src)):
                            os.remove(src)
                            return None
                    except OSError:
                        pass
                    raise
                _time.sleep(0.05 * (i + 1))

    os.replace = _win_replace

    # ---- ctypes.CDLL(None) / libSystem
    # can_clone() asks the process itself for clonefile; uepak.py decrypts through libSystem's
    # CommonCrypto. Neither exists here. An empty library makes the clone probe fall back to
    # plain copies, and CommonCrypto's CCCrypt is backed by Windows' own AES (CNG) so Unreal
    # pak indexes still decode.
    class _NoLib:
        def __getattr__(self, name):
            raise AttributeError(f'{name} (no process-wide C library on Windows)')

    class _CCCrypt:
        restype = argtypes = None

        def __call__(self, op, alg, options, key, keylen, iv, data, datalen, out, outlen, moved):
            if alg != 0 or options not in (0, 2):
                return -4301        # kCCUnimplemented: only AES (0) in ECB mode (2), unpadded
            from ctypes import wintypes, byref, c_void_p, c_ulong, create_unicode_buffer
            bc = ctypes.WinDLL('bcrypt')
            h = c_void_p(); hk = c_void_p(); res = c_ulong()
            if bc.BCryptOpenAlgorithmProvider(byref(h), ctypes.c_wchar_p('AES'), None, 0):
                return -4300
            try:
                mode = create_unicode_buffer('ChainingModeECB')
                bc.BCryptSetProperty(h, ctypes.c_wchar_p('ChainingMode'), mode,
                                     ctypes.sizeof(mode), 0)
                k = bytes(key)[:keylen]
                if bc.BCryptGenerateSymmetricKey(h, byref(hk), None, 0, k, len(k), 0):
                    return -4300
                src = bytes(data)[:datalen]
                fn = bc.BCryptDecrypt if op == 1 else bc.BCryptEncrypt
                if fn(hk, src, len(src), None, None, 0, out, outlen, byref(res), 0):
                    return -4300
                moved._obj.value = res.value if hasattr(moved, '_obj') else res.value
                return 0
            finally:
                if hk:
                    bc.BCryptDestroyKey(hk)
                bc.BCryptCloseAlgorithmProvider(h, 0)

    class _LibSystem:
        CCCrypt = _CCCrypt()

    import ctypes
    _CDLL = ctypes.CDLL

    def _cdll(name, *a, **k):
        if name is None:
            return _NoLib()
        if isinstance(name, str) and name.endswith('libSystem.B.dylib'):
            return _LibSystem()
        return _CDLL(name, *a, **k)

    ctypes.CDLL = _cdll

    # ---- the command map
    _CACHE = {}

    def _resolve(rest):
        """xcrun -sdk <sdk> metal / metallib straight to the Windows tool, without a Python
        process per call: a shader build makes thousands of them."""
        if len(rest) < 3 or rest[0] not in ('-sdk', '--sdk') or rest[2] not in ('metal', 'metallib'):
            return None
        if 'modules' not in _CACHE:
            if _PKG not in sys.path:
                sys.path.insert(0, _PKG)
            import xcrun_shim, toolchain
            _CACHE['modules'] = (xcrun_shim, toolchain)
        x, t = _CACHE['modules']
        sdk, tool = rest[1], rest[2]
        key = (sdk, tool)
        if key not in _CACHE:
            _CACHE[key] = t.metal_tool(tool, sdk)
        exe = _CACHE[key]
        if not exe:
            return None
        return [str(exe)] + (x.metal_args(sdk, rest[3:]) if tool == 'metal' else rest[3:])

    def _map(args):
        if isinstance(args, (str, bytes)) or not args:
            return args
        args = [os.fspath(a) if isinstance(a, os.PathLike) else a for a in args]
        if not isinstance(args[0], str):
            return args
        head = args[0].replace('\\', '/')
        base = head.rsplit('/', 1)[-1].lower()
        if base in ('xcrun', 'xcrun.exe'):
            return _resolve(args[1:]) or [sys.executable, _XCRUN] + args[1:]
        if base == 'dmsh_xlate' and '/dmsh_xlate_bin/' in head:
            # an absolute path, not `which`: a .NET SDK the app installed is not on PATH
            import toolchain as tc
            dn = tc.dotnet_dir()
            dotnet = str(dn / 'dotnet.exe') if dn else (shutil.which('dotnet') or 'dotnet')
            return [dotnet, args[0] + '.dll'] + args[1:]
        if base in ('python3', 'python3.exe'):
            return [sys.executable] + args[1:]
        if base in ('bash', 'bash.exe') and len(args) > 1 and \
                args[1].replace('\\', '/').endswith('dm/ios/tools/build_ipa.sh'):
            return [sys.executable, _BUILD_APP] + args[2:]
        if base in ('which', 'which.exe') and len(args) == 2:
            return [sys.executable, '-c',
                    'import shutil,sys; p=shutil.which(sys.argv[1]); print(p or ""); '
                    'sys.exit(0 if p else 1)', args[1]]
        return args

    # A macOS-only Metal compile (the Mac shader libraries) is never packed into the iOS app;
    # what the iOS build reads from those outputs is the MSL text and the JSON beside it. The
    # reference implementation writes an empty file instead of starting a process, which halves
    # the shader stage. NSPB_MAC_METAL=1 compiles them for real.
    _run = subprocess.run

    def _run_fast(args, *a, **k):
        if (not os.environ.get('NSPB_MAC_METAL') and isinstance(args, (list, tuple))
                and len(args) > 4 and isinstance(args[0], str)
                and args[0].replace('\\', '/').rsplit('/', 1)[-1].lower() in ('xcrun', 'xcrun.exe')
                and args[1] in ('-sdk', '--sdk') and str(args[2]).startswith('macosx')
                and args[3] in ('metal', 'metallib') and '-o' in args):
            out = os.fspath(args[list(args).index('-o') + 1])
            with open(out, 'wb'):
                pass
            return subprocess.CompletedProcess(args, 0,
                                               b'' if not k.get('text') else '',
                                               b'' if not k.get('text') else '')
        return _run(args, *a, **k)

    subprocess.run = _run_fast

    _init = subprocess.Popen.__init__

    def _popen_init(self, args, *a, **k):
        if os.environ.get('NSPB_SHIM_TRACE'):
            print('nspb shim:', args, '->', _map(args), file=sys.stderr)
        _init(self, _map(args), *a, **k)

    subprocess.Popen.__init__ = _popen_init

    # ---- pwd
    # scripts/build_ipa_from_nsp.py imports pwd at module level (a POSIX-only module), so the
    # upstream file cannot even be loaded on Windows without this stand-in. It is only used to
    # recover HOME from the password database when the environment has none.
    if 'pwd' not in sys.modules:
        import types
        _pwd = types.ModuleType('pwd')

        class struct_passwd(tuple):
            __slots__ = ()

            @property
            def pw_dir(self):
                return self[5]

        def getpwuid(uid):
            home = os.environ.get('USERPROFILE') or os.path.expanduser('~')
            name = os.environ.get('USERNAME') or 'user'
            return struct_passwd((name, 'x', uid if uid is not None else 0, 0, '', home, ''))

        _pwd.struct_passwd = struct_passwd
        _pwd.getpwuid = getpwuid
        _pwd.getpwnam = lambda name: getpwuid(0)
        sys.modules['pwd'] = _pwd
'''


def install(shim_dir: Path, python_exe: str | None = None) -> None:
    """Write `sitecustomize.py` and the `.cmd` stand-ins into `shim_dir`.

    Idempotent: the files are rewritten only when their bytes differ, so an incremental build
    does not invalidate anything keyed on their mtime.

    The generated `sitecustomize.py` needs to know where this package lives, because it is
    written into a separate folder (the app's data dir) while the modules it calls stay in the
    package. That path is baked in as a literal, so the file does not depend on the environment
    of whichever process imports it.
    """
    shim_dir.mkdir(parents=True, exist_ok=True)
    pkg = str(Path(__file__).resolve().parent)
    body = _SITECUSTOMIZE_SRC.replace(
        "    _PKG = os.environ.get('NSPB_WIN_DIR') or _HERE\n",
        '    _PKG = os.environ.get(\'NSPB_WIN_DIR\') or ' + repr(pkg) + '\n')
    sc = shim_dir / SITECUSTOMIZE
    if not sc.is_file() or sc.read_text(encoding='utf-8') != body:
        sc.write_text(body, encoding='utf-8', newline='\n')
    py = python_exe or sys.executable
    here = Path(pkg)
    for name, target in (('xcrun', here / 'xcrun_shim.py'),
                         ('xcodebuild', here / 'xcodebuild_shim.py'),
                         ('xcodegen', here / 'xcodegen_shim.py')):
        body_cmd = (f'@echo off\r\n'
                    f'"{py}" "{target}" %*\r\n')
        p = shim_dir / f'{name}.cmd'
        if not p.is_file() or p.read_text(encoding='utf-8', errors='replace') != body_cmd:
            p.write_text(body_cmd, encoding='utf-8', newline='')
    # a `python3.cmd` so the pipeline's `python3` spelling works in a shell too
    p = shim_dir / 'python3.cmd'
    body_py = f'@echo off\r\n"{py}" %*\r\n'
    if not p.is_file() or p.read_text(encoding='utf-8', errors='replace') != body_py:
        p.write_text(body_py, encoding='utf-8', newline='')


def shim_dir() -> Path:
    """Where the stand-ins live: inside the app's data folder, so no repository file changes."""
    base = Path(os.environ.get('LOCALAPPDATA', Path.home() / 'AppData' / 'Local'))
    return base / 'NS Port Builder' / 'shim'


def build_env(base: dict[str, str] | None = None, python_exe: str | None = None) -> dict[str, str]:
    """The environment a Windows build runs with.

    `PYTHONPATH` puts the shim first so every child Python loads it; `PATH` puts the `.cmd`
    stand-ins first so a tool spawned by name resolves to them; the `NSPB_*` variables tell
    `toolchain.py` where the LLVM / SDK / Metal folders are, which is how the user's
    `toolchain.json` reaches a process that never reads the app's config.
    """
    env = dict(base if base is not None else os.environ)
    sd = shim_dir()
    install(sd, python_exe)

    parts = [str(sd)]
    llvm = tc.llvm_dir()
    if llvm:
        parts.append(str(llvm / 'bin'))
        env['NSPB_LLVM_DIR'] = str(llvm)
        lld = tc.ld64_lld() or (llvm / 'bin' / 'ld64.lld.exe')
        if Path(lld).is_file():
            parts.append(str(Path(lld).parent))
    for name in ('spirv-cross', 'zstd', 'glslangValidator'):
        p = tc.find_exe(name)
        if p:
            parts.append(str(p.parent))
            if name == 'spirv-cross': env.setdefault('SPIRV_CROSS', str(p))
    # tc.dotnet_dir() first: it knows about the SDK the app installed for itself, which is not on
    # PATH and not in Program Files. `which` alone missed it, so `dotnet build` and the shader
    # translator failed on a machine that had just installed .NET through this app.
    if dn := tc.dotnet_dir():
        parts.append(str(dn))
        env['DOTNET_ROOT'] = env['DOTNET_ROOT_X64'] = str(dn)
    elif dn := shutil.which('dotnet'):
        parts.append(str(Path(dn).parent))

    env['PATH'] = os.pathsep.join(dict.fromkeys(parts + [env.get('PATH', '')]))
    env['PYTHONPATH'] = os.pathsep.join(
        dict.fromkeys([str(sd)] + [p for p in env.get('PYTHONPATH', '').split(os.pathsep) if p]))
    env.setdefault('PYTHONUTF8', '1')     # the pipeline reads and writes UTF-8 without naming it
    env.setdefault('PYTHONIOENCODING', 'utf-8')

    sdk = tc.ios_sdk()
    if sdk:
        env['NSPB_IOS_SDK'] = str(sdk)
        env['IPHONEOS_SDK_DIR'] = str(sdk)     # what platform_util.ios_sdk_ok already checks
    if m := tc.metal_dir():
        env['NSPB_METAL_DIR'] = str(m)
    exe = tc.metal_tool('metal')
    if exe:
        env['METAL_EXE'] = str(exe)
    with_lib = tc.metal_tool('metallib')
    if with_lib:
        env['METALLIB_EXE'] = str(with_lib)

    # the shader build spawns one metal.exe per shader and each start costs ~0.1 s on Windows,
    # so keep every core busy rather than the upstream default of 8
    env.setdefault('J', str(max(8, 2 * (os.cpu_count() or 4))))
    return env


def verify_shim(env: dict[str, str]) -> tuple[bool, str]:
    """Prove the shim loads in a child interpreter before a build relies on it."""
    try:
        r = subprocess.run([env.get('NSPB_PYTHON') or sys.executable, '-c',
                            'import sys; sys.exit(0 if "sitecustomize" in sys.modules else 3)'],
                           capture_output=True, text=True, env=env, timeout=60)
    except (OSError, subprocess.SubprocessError) as e:
        return False, f'cannot run a probe interpreter: {e}'
    if r.returncode == 0:
        return True, 'shim loads in child interpreters'
    return False, ('the shim did not load in a child interpreter (sitecustomize is shadowed by '
                   'another one on PYTHONPATH?)')
