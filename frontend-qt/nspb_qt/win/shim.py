    def _split_dm_games_dir(raw):
        out = []
        for semi in str(raw or '').split(';'):
            parts = semi.split(':')
            i = 0
            while i < len(parts):
                cur = parts[i]
                if len(cur) == 1 and cur.isalpha() and i + 1 < len(parts) and parts[i + 1][:1] in ('\\', '/'):
                    out.append(cur + ':' + parts[i + 1])
                    i += 2
                else:
                    if cur:
                        out.append(cur)
                    i += 1
        return out

